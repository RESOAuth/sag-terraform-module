#!/usr/bin/env node
// Bundle one of smart-access-gateway's Worker entry points into the single
// module `cloudflare_workers_script` can upload.
//
// `adapters/cloudflare/worker.js` is not a bundle: it imports `../../src/index.js`
// and re-exports the Durable Object class from a sibling file. Terraform cannot
// bundle, and the Cloudflare API will not accept a multi-file upload built by
// hand, so this shells out to wrangler's own esbuild pipeline with
// `--dry-run --outdir`, which needs no credentials and uploads nothing. The
// upload itself stays a Terraform resource; only the bundling is a build step,
// exactly as scripts/fetch-release.mjs is for the Lambda package.
//
// Invoked as a Terraform `data "external"` source from modules/cloudflare.
// Handles no secret: the wrangler config it writes carries the script name and
// entry point and nothing else, and every SAG variable is a Terraform-managed
// binding on the script resource instead.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

function fail(message) {
  process.stderr.write(`bundle-worker: ${message}\n`);
  process.exit(1);
}

async function readQuery() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  const text = Buffer.concat(chunks).toString('utf8').trim();
  if (!text) fail('no query on stdin; this script is invoked by Terraform, not by hand');
  try {
    return JSON.parse(text);
  } catch (err) {
    fail(`query is not JSON: ${err.message}`);
  }
}

const query = await readQuery();
const sourceDir = String(query.source_dir || '');
const entry = String(query.entry || '');
const name = String(query.name || 'sag');
const compatibilityDate = String(query.compatibility_date || '2026-01-01');
const compatibilityFlags = String(query.compatibility_flags || '')
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean);

if (!sourceDir || !existsSync(sourceDir)) fail(`no such source directory: ${sourceDir}`);
const entryPath = join(sourceDir, entry);
if (!existsSync(entryPath)) fail(`the resolved source has no ${entry}`);

// Beside the staged source, so it is cleaned up with the release cache and
// survives between the plan that computes it and the apply that reads it.
const bundleName = basename(entry, '.js');
const outDir = join(sourceDir, '..', 'bundles', bundleName);
const configPath = join(sourceDir, '..', `wrangler.bundle.${bundleName}.toml`);
const npmCache = join(sourceDir, '..', 'npm-cache', bundleName);

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

writeFileSync(
  configPath,
  [
    '# Generated by scripts/bundle-worker.mjs purely to drive `wrangler deploy',
    '# --dry-run`. Nothing deploys from it: bindings, routes and secrets are all',
    '# Terraform-managed or set out-of-band, and none of them appear here.',
    `name = "${name}"`,
    `main = "${entryPath}"`,
    `compatibility_date = "${compatibilityDate}"`,
    `compatibility_flags = [${compatibilityFlags.map((f) => `"${f}"`).join(', ')}]`,
    '',
  ].join('\n'),
);

try {
  execFileSync(
    process.env.SAG_WRANGLER || 'npx',
    process.env.SAG_WRANGLER
      ? ['deploy', '--dry-run', `--outdir=${outDir}`, '--config', configPath]
      : ['--yes', 'wrangler@4', 'deploy', '--dry-run', `--outdir=${outDir}`, '--config', configPath],
    {
      cwd: sourceDir,
      stdio: ['ignore', 'pipe', 'pipe'],
      // Terraform evaluates the main and HSM data sources concurrently. npx
      // cannot safely populate one _npx directory from both processes, so
      // isolate their caches while retaining each one across later plans.
      env: {
        ...process.env,
        ...(process.env.SAG_WRANGLER ? {} : { npm_config_cache: npmCache }),
        WRANGLER_SEND_METRICS: 'false',
        CI: '1',
      },
      maxBuffer: 64 * 1024 * 1024,
    },
  );
} catch (err) {
  fail(`wrangler could not bundle ${entry}: ${String(err.stderr || err.message).slice(0, 2000)}`);
}

const bundlePath = join(outDir, basename(entry));
if (!existsSync(bundlePath)) fail(`wrangler produced no ${basename(entry)} in ${outDir}`);

// The source map is not uploaded and would only inflate the script.
rmSync(`${bundlePath}.map`, { force: true });

const sha256 = createHash('sha256').update(readFileSync(bundlePath)).digest('hex');

process.stdout.write(`${JSON.stringify({ path: bundlePath, sha256 })}\n`);
